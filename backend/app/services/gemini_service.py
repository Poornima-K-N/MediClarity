class GeminiError(Exception):
    """Base exception for Gemini service errors."""
    def __init__(self, message, status_code=500):
        super().__init__(message)
        self.message = message
        self.status_code = status_code


class GeminiConfigurationError(GeminiError):
    def __init__(self, detail=""):
        msg = (
            "Gemini API key is not configured in backend environment variables. "
            "Please configure the GEMINI_API_KEY environment variable to enable AI extraction."
        )
        if detail:
            msg += f" ({detail})"
        super().__init__(msg, status_code=503)


class GeminiExtractionError(GeminiError):
    def __init__(self, message="Failed to parse document with Gemini API.", status_code=502):
        super().__init__(message, status_code=status_code)


