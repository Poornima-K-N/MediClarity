import os
import sys
import json
import unittest
from unittest.mock import patch, MagicMock

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from app import create_app
from app.config import Config
from app.services.gemini_service import (
    clean_json_response,
    extract_structured_medical_data,
    GeminiConfigurationError,
    GeminiExtractionError
)

class TestGeminiIntegration(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.app = create_app()
        cls.app.config['TESTING'] = True
        cls.client = cls.app.test_client()

    def test_clean_json_response_clean(self):
        """Test parsing valid JSON without code fences."""
        raw = '{"document_type": "lab_report", "lab_tests": []}'
        parsed = clean_json_response(raw)
        self.assertEqual(parsed['document_type'], 'lab_report')

    def test_clean_json_response_with_markdown_fences(self):
        """Test stripping markdown ```json code fences."""
        raw = '```json\n{"document_type": "prescription", "medications": [{"name": "Amoxicillin"}]}\n```'
        parsed = clean_json_response(raw)
        self.assertEqual(parsed['document_type'], 'prescription')
        self.assertEqual(len(parsed['medications']), 1)

    def test_clean_json_response_invalid(self):
        """Test error handling when JSON is malformed."""
        with self.assertRaises(GeminiExtractionError):
            clean_json_response("This is not JSON at all")

    def test_missing_api_key_raises_configuration_error(self):
        """Verify 503 configuration error is raised when GEMINI_API_KEY is unset."""
        with patch.object(Config, 'GEMINI_API_KEY', ''):
            with self.assertRaises(GeminiConfigurationError):
                extract_structured_medical_data("Sample text", custom_api_key='')

    def test_empty_text_raises_extraction_error(self):
        """Verify 400 extraction error is raised when input text is empty."""
        with self.assertRaises(GeminiExtractionError):
            extract_structured_medical_data("   ", custom_api_key='mock_key')

    @patch('app.services.gemini_service.genai.Client')
    def test_structured_extraction_success(self, mock_client_cls):
        """Verify full structured extraction parsing with mocked Gemini client."""
        mock_client = MagicMock()
        mock_client_cls.return_value = mock_client

        simulated_gemini_response = {
            "document_type": "lab_report",
            "document_title": "Complete Blood Count",
            "detected_date": "2026-11-10",
            "lab_or_clinic": "Metropolitan Health Laboratory",
            "summary_overview": "CBC panel with normal hemoglobin and platelets.",
            "lab_tests": [
                {
                    "test_name": "Hemoglobin",
                    "observed_value": "14.5",
                    "unit": "g/dL",
                    "reference_range": "13.5 - 17.5",
                    "flag": "Normal",
                    "flag_reason": "Explicitly stated as normal"
                },
                {
                    "test_name": "Platelets",
                    "observed_value": "250,000",
                    "unit": "/mcL",
                    "reference_range": "150,000 - 450,000",
                    "flag": "Normal",
                    "flag_reason": None
                }
            ],
            "medications": [],
            "disclaimer": "This structured extraction is generated by MediClarity AI..."
        }

        mock_response = MagicMock()
        mock_response.text = json.dumps(simulated_gemini_response)
        mock_client.models.generate_content.return_value = mock_response

        result = extract_structured_medical_data(
            "Sample CBC report text",
            custom_api_key="mock_test_key"
        )

        self.assertEqual(result['document_type'], 'lab_report')
        self.assertEqual(len(result['lab_tests']), 2)
        self.assertEqual(result['lab_tests'][0]['test_name'], 'Hemoglobin')
        self.assertEqual(result['lab_tests'][0]['observed_value'], '14.5')
        self.assertEqual(result['lab_tests'][0]['unit'], 'g/dL')
        self.assertEqual(result['lab_tests'][0]['reference_range'], '13.5 - 17.5')
        self.assertEqual(result['lab_tests'][0]['flag'], 'Normal')

    def test_api_endpoint_missing_text(self):
        """Verify endpoint returns 400 when text payload is missing."""
        res = self.client.post(
            '/api/analyze-medical-text',
            json={},
            content_type='application/json'
        )
        self.assertEqual(res.status_code, 400)
        data = res.get_json()
        self.assertIn('No medical document text provided', data['error'])

    def test_api_endpoint_missing_key_returns_503(self):
        """Verify endpoint returns 503 and clear guidance when GEMINI_API_KEY is not configured."""
        with patch.object(Config, 'GEMINI_API_KEY', ''):
            res = self.client.post(
                '/api/analyze-medical-text',
                json={'text': 'Hemoglobin 14.2 g/dL'},
                content_type='application/json'
            )
            self.assertEqual(res.status_code, 503)
            data = res.get_json()
            self.assertTrue(data.get('missing_key'))
            self.assertIn('GEMINI_API_KEY', data['error'])

    @patch('app.routes.document.Config')
    @patch('app.routes.document.extract_structured_medical_data')
    def test_api_endpoint_success(self, mock_extract, mock_config):
        """Verify endpoint returns 200 and structured data on successful extraction."""
        mock_config.GEMINI_API_KEY = "test_key"
        mock_extract.return_value = {
            "document_type": "prescription",
            "document_title": "Clinic Prescription",
            "detected_date": None,
            "lab_or_clinic": "MediClarity Health",
            "summary_overview": "Amoxicillin course",
            "lab_tests": [],
            "medications": [
                {
                    "name": "Amoxicillin",
                    "dosage": "500 mg",
                    "form": "capsule",
                    "frequency": "three times daily",
                    "duration": "7 days",
                    "instructions": "Take with meals",
                    "refills": "0"
                }
            ],
            "disclaimer": "Test disclaimer"
        }

        res = self.client.post(
            '/api/analyze-medical-text',
            json={'text': 'Amoxicillin 500mg, 1 cap TID x 7d with meals'},
            content_type='application/json'
        )
        self.assertEqual(res.status_code, 200)
        data = res.get_json()
        self.assertEqual(data['status'], 'success')
        self.assertEqual(data['structured_data']['document_type'], 'prescription')
        self.assertEqual(len(data['structured_data']['medications']), 1)
        self.assertEqual(data['structured_data']['medications'][0]['name'], 'Amoxicillin')
        self.assertEqual(data['structured_data']['medications'][0]['dosage'], '500 mg')


if __name__ == '__main__':
    unittest.main()
